test('tie-break by roster index ascending, ranking deterministic', () => {
  const g = baseGen();
  g.rosterCount = 3;
  g.slugs = ['aa', 'bb', 'cc']; g.names = ['Aa', 'Bb', 'Cc']; g.icons = ['aa', 'bb', 'cc'];
  g.pop = [0.3, 0.3, 0.3]; g.poolIdx = [0, 1, 2];
  g.entries = [{ roles: ['1'], tier: { '1': 'dedicated' } },
    { roles: ['1'], tier: { '1': 'dedicated' } }, { roles: ['1'], tier: { '1': 'dedicated' } }];
  g.mu = ['0:0.5:0,1:0.5:0,2:0.5:0', '0:0.5:0,1:0.5:0,2:0.5:0', '0:0.5:0,1:0.5:0,2:0.5:0'];
  g.syn = g.mu;
  g.prior = [0.4, 0.4, 0.9];
  g.gates.rules = [];
  const ranked = PS.rankRole(g, EMPTY, '1');
  // cc wins on prior 0.9, aa and bb tie fully and order by idx
  assert.deepEqual(ranked.map(r => r.idx), [2, 0, 1]);
  assert.deepEqual(PS.rankRole(g, EMPTY, '1'), ranked);
});

test('rankRole filters by role and taken heroes, flags hard gates', () => {
  const g = baseGen();
  const empty = PS.rankRole(g, EMPTY, '3');
  assert.deepEqual(empty.map(r => r.idx).sort((a, b) => a - b), [4, 6, 7]);
  const mid = { allies: [1, 2], enemies: [3, 4, 7], banned: [5], role: '1' };
  const one = PS.rankRole(g, mid, '1');
  assert.deepEqual(one.map(r => r.idx), [0]);
  assert.equal(one[0].hardGated, true);
});
