test('condition vocabulary, visible all/any/none, ally, counts, aoe, note_only', () => {
  const all = { id: 'v1', target: 'alpha', roles: ['1'],
    when: [{ kind: 'enemyVisible', heroes: ['delta', 'echo'] }], action: 'bonus' };
  assert.equal(fires(all, { allies: [], enemies: [3, 4], banned: [], role: '1' }), true);
  assert.equal(fires(all, { allies: [], enemies: [3], banned: [], role: '1' }), false);
  const none = { id: 'v2', target: 'alpha', roles: ['1'],
    when: [{ kind: 'enemyVisibleNone', heroes: ['delta'] }], action: 'bonus' };
  assert.equal(fires(none, { allies: [], enemies: [7], banned: [], role: '1' }), true);
  assert.equal(fires(none, { allies: [], enemies: [3], banned: [], role: '1' }), false);
  const ally = { id: 'v3', target: 'alpha', roles: ['1'],
    when: [{ kind: 'allyVisibleAny', heroes: ['bravo'] }], action: 'bonus' };
  assert.equal(fires(ally, { allies: [1], enemies: [], banned: [], role: '1' }), true);
  assert.equal(fires(ally, { allies: [2], enemies: [], banned: [], role: '1' }), false);
  const ecmin = { id: 'v4', target: 'alpha', roles: ['1'],
    when: [{ kind: 'enemyCountMin', count: 3 }], action: 'bonus' };
  assert.equal(fires(ecmin, { allies: [], enemies: [3, 4, 7], banned: [], role: '1' }), true);
  assert.equal(fires(ecmin, { allies: [], enemies: [3, 4], banned: [], role: '1' }), false);
  const ecmax = { id: 'v5', target: 'alpha', roles: ['1'],
    when: [{ kind: 'enemyCountMax', count: 1 }], action: 'bonus' };
  assert.equal(fires(ecmax, { allies: [], enemies: [3], banned: [], role: '1' }), true);
  assert.equal(fires(ecmax, { allies: [], enemies: [3, 4], banned: [], role: '1' }), false);
  const countMin = { id: 'c2', target: 'hotel', roles: ['1'],
    when: [{ kind: 'enemyVisibleAnyCountMin', heroes: ['delta', 'echo'], count: 2 }], action: 'bonus' };
  assert.equal(fires(countMin, { allies: [], enemies: [3], banned: [], role: '1' }), false);
  assert.equal(fires(countMin, { allies: [], enemies: [3, 4], banned: [], role: '1' }), true);
  const only = { id: 'v6', target: 'alpha', roles: ['1'],
    when: [{ kind: 'enemyVisibleAny', heroes: ['delta'] }], action: 'note_only', note: 'heads up' };
  const r = PS.scoreCandidate(withRules([only]),
    { allies: [], enemies: [3], banned: [], role: '1' }, '1', 0);
  assert.deepEqual(r.notes, ['heads up']);
  assert.deepEqual(r.firedRuleIds, ['v6']);
  close(r.terms.gateDelta, 0);
  assert.equal(r.hardGated, false);
});

