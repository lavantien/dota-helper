package eval

import (
	"math"

	"poolguide/internal/analytics"
	"poolguide/internal/config"
	"poolguide/internal/gates"
)

// RoleRank is the picked hero's standing inside one of its roles.
type RoleRank struct {
	Rank int // 1-based, 0 when the pick itself was gated out of that role
	N    int
}

// PickEval is one pool pick as the picker would have seen it.
type PickEval struct {
	MatchID    int64
	Seq        int
	Idx        int // roster index of the picked hero
	Radiant    bool
	K          int // visible opposing picks at pick time
	A          int // pool allies on the picking side at pick time
	PoolN      int // eligible pool candidates plus the picked hero when it is itself eligible
	PoolRank   int // 1-based in the full-pool ranking, 0 when gated out
	Percentile float64
	RoleRank   map[string]RoleRank
	Score      float64 // at-pick score in the full-pool ranking
}

// Ranked reports whether the percentile is defined (a ranked pick against
// more than one candidate).
func (p PickEval) Ranked() bool { return p.PoolRank > 0 && p.PoolN > 1 }

// MatchReplay is the pick-by-pick record of one match plus its draft-level
// advantage: the radiant sum of at-pick scores minus the dire sum.
type MatchReplay struct {
	MatchID    int64
	RadiantWin bool
	Picks      []PickEval
	Advantage  float64
}

// inertGated mirrors the js twin's -Infinity baseline for
// roleCandidatesGated: the condition never holds while counting the gated
// baseline, so the count cannot recurse through itself.
const inertGated = math.MinInt

// draftState is the visible draft at one pick, in roster indices. Allies
// are pool-only (the documented approximation: the picker's syn rows live
// within the pool), enemies are every opposing pick, taken covers picks
// and bans. The slug views are built once per state because gate
// evaluation runs per candidate per role.
type draftState struct {
	allies []int
	taken  []int
	banned []string
	enemy  map[int]bool
	enems  []int

	allySlugs, enemSlugs, takenSlugs []string
	slugsBuilt                        bool
}

func newDraftState() draftState {
	return draftState{enemy: map[int]bool{}}
}

func (s *draftState) addEnemy(idx int) {
	if !s.enemy[idx] {
		s.enemy[idx] = true
		s.enems = append(s.enems, idx)
	}
}

func slugsOf(m *Model, idxs []int) []string {
	out := make([]string, len(idxs))
	for i, idx := range idxs {
		out[i] = m.Slugs[idx]
	}
	return out
}

func (s *draftState) buildSlugs(m *Model) {
	if s.slugsBuilt {
		return
	}
	s.slugsBuilt = true
	s.allySlugs = slugsOf(m, s.allies)
	s.enemSlugs = slugsOf(m, s.enems)
	s.takenSlugs = slugsOf(m, s.taken)
}

// gateRules flattens the doc in authored-then-autogenerated order.
func gateRules(doc *gates.Doc) []gates.Rule {
	return append(append([]gates.Rule(nil), doc.Rules...), doc.Autogenerated...)
}

func gateState(s draftState, role string, candidatesGated int) gates.DraftState {
	return gates.DraftState{
		VisibleEnemies:  s.enemSlugs,
		Allies:          s.allySlugs,
		Taken:           s.takenSlugs,
		Banned:          s.banned,
		Role:            role,
		CandidatesGated: candidatesGated,
	}
}

// gatedCount mirrors gatedCount in picker-score.js: every pool hero with
// the role, taken or not, hard-gated under the inert view of this state.
func gatedCount(cfg *config.Config, m *Model, rules []gates.Rule, s draftState, role string) int {
	n := 0
	for _, idx := range m.PoolIdx {
		if !hasRole(m.Roles[idx], role) {
			continue
		}
		if gates.Evaluate(rules, m.Slugs[idx], gateState(s, role, inertGated), cfg).HardGated {
			n++
		}
	}
	return n
}

func hasRole(roles []string, role string) bool {
	for _, r := range roles {
		if r == role {
			return true
		}
	}
	return false
}

// evalRole picks the first config role the hero survives in; ok is false
// when hard-gated in every role it plays.
func evalRole(cfg *config.Config, m *Model, rules []gates.Rule, s draftState, idx int) (string, bool) {
	for _, role := range m.Roles[idx] {
		if !gates.Evaluate(rules, m.Slugs[idx], gateState(s, role, inertGated), cfg).HardGated {
			return role, true
		}
	}
	return "", false
}

// scorePick ranks the candidate field for one state and returns the picked
// hero's standing plus its at-pick score. The picked hero is scored even
// when gated out of its own field: the at-pick score still feeds the
// advantage sums.
func scorePick(cfg *config.Config, m *Model, rules []gates.Rule, s draftState, picked int) PickEval {
	eval := PickEval{Idx: picked, RoleRank: map[string]RoleRank{}, K: len(s.enems), A: len(s.allies)}
	taken := map[int]bool{}
	for _, idx := range s.taken {
		taken[idx] = true
	}
	gatedMemo := map[string]int{}
	deltaFor := func(role string, idx int) float64 {
		gc, ok := gatedMemo[role]
		if !ok {
			gc = gatedCount(cfg, m, rules, s, role)
			gatedMemo[role] = gc
		}
		return gates.Evaluate(rules, m.Slugs[idx], gateState(s, role, gc), cfg).Delta
	}
	draft := analytics.Draft{
		RosterSize:     m.RosterSize,
		Pop:            m.Pop,
		VisibleEnemies: s.enems,
		Allies:         s.allies,
		Taken:          s.taken,
	}

	var cands []analytics.Candidate
	pickedRole, eligible := evalRole(cfg, m, rules, s, picked)
	if pickedRole == "" {
		pickedRole = m.Roles[picked][0]
	}
	for pi, idx := range m.PoolIdx {
		if taken[idx] || idx == picked {
			continue
		}
		role, ok := evalRole(cfg, m, rules, s, idx)
		if !ok {
			continue
		}
		cands = append(cands, analytics.Candidate{
			Idx: idx, Role: role, Prior: m.Prior[pi], GateDelta: deltaFor(role, idx),
			Mu: m.Mu[pi], Syn: m.Syn[pi],
		})
	}
	pickedPos := m.PoolPos[picked]
	pickedCand := analytics.Candidate{
		Idx: picked, Role: pickedRole, Prior: m.Prior[pickedPos],
		GateDelta: deltaFor(pickedRole, picked), Mu: m.Mu[pickedPos], Syn: m.Syn[pickedPos],
	}
	if eligible {
		cands = append(cands, pickedCand)
		for i, t := range analytics.Rank(cands, draft, cfg.Weights, cfg.Score) {
			if t.Idx == picked {
				eval.PoolRank = i + 1
				break
			}
		}
	}
	// the at-pick score exists even when the pick was gated out of its own
	// field: it still feeds the advantage sums
	eval.Score = analytics.Score(pickedCand, draft, cfg.Weights, cfg.Score).Score
	eval.PoolN = len(cands)

	for _, role := range m.Roles[picked] {
		rr := roleStandings(cfg, m, rules, s, draft, taken, role, picked, deltaFor)
		eval.RoleRank[role] = rr
	}
	if eval.PoolN > 1 && eval.PoolRank > 0 {
		eval.Percentile = (float64(eval.PoolN) - float64(eval.PoolRank)) / float64(eval.PoolN-1)
	}
	return eval
}

// roleStandings ranks the picked hero inside one role's candidate field.
func roleStandings(cfg *config.Config, m *Model, rules []gates.Rule, s draftState,
	draft analytics.Draft, taken map[int]bool, role string, picked int, deltaFor func(string, int) float64) RoleRank {
	var cands []analytics.Candidate
	for pi, idx := range m.PoolIdx {
		if taken[idx] || idx == picked || !hasRole(m.Roles[idx], role) {
			continue
		}
		if gates.Evaluate(rules, m.Slugs[idx], gateState(s, role, inertGated), cfg).HardGated {
			continue
		}
		cands = append(cands, analytics.Candidate{
			Idx: idx, Role: role, Prior: m.Prior[pi], GateDelta: deltaFor(role, idx),
			Mu: m.Mu[pi], Syn: m.Syn[pi],
		})
	}
	rr := RoleRank{}
	if !gates.Evaluate(rules, m.Slugs[picked], gateState(s, role, inertGated), cfg).HardGated {
		pos := m.PoolPos[picked]
		cands = append(cands, analytics.Candidate{
			Idx: picked, Role: role, Prior: m.Prior[pos],
			GateDelta: deltaFor(role, picked), Mu: m.Mu[pos], Syn: m.Syn[pos],
		})
		for i, t := range analytics.Rank(cands, draft, cfg.Weights, cfg.Score) {
			if t.Idx == picked {
				rr.Rank = i + 1
				break
			}
		}
	}
	rr.N = len(cands)
	return rr
}

// sideTallies walks one draft and reports, per side, the pool picks and all
// picks in seq order, plus the combined taken list and ban slugs.
type sideTallies struct {
	radiantPool, direPool []int
	radiantAll, direAll   []int
	taken                 []int
	banned                []string
}

func tallySides(m *Model, mt Match) sideTallies {
	var t sideTallies
	for _, ev := range mt.Events {
		idx, ok := m.IdxOf[ev.Slug]
		if !ok {
			continue
		}
		t.taken = append(t.taken, idx)
		if !ev.IsPick {
			t.banned = append(t.banned, ev.Slug)
			continue
		}
		_, pool := m.PoolPos[idx]
		if ev.IsRadiant {
			t.radiantAll = append(t.radiantAll, idx)
			if pool {
				t.radiantPool = append(t.radiantPool, idx)
			}
		} else {
			t.direAll = append(t.direAll, idx)
			if pool {
				t.direPool = append(t.direPool, idx)
			}
		}
	}
	return t
}

// stateBefore builds the information state for the event at position i:
// everything that happened strictly earlier.
func stateBefore(m *Model, mt Match, i int) draftState {
	s := newDraftState()
	ev := mt.Events[i]
	for _, prev := range mt.Events[:i] {
		idx, ok := m.IdxOf[prev.Slug]
		if !ok {
			continue
		}
		if !prev.IsPick {
			s.banned = append(s.banned, prev.Slug)
			s.taken = append(s.taken, idx)
			continue
		}
		s.taken = append(s.taken, idx)
		if prev.IsRadiant != ev.IsRadiant {
			s.addEnemy(idx)
		} else if _, pool := m.PoolPos[idx]; pool {
			s.allies = append(s.allies, idx)
		}
	}
	s.buildSlugs(m)
	return s
}

// finalSetState builds the hindsight state for one pool pick: every pick of
// the opposing side visible, the side's other pool picks as allies, and the
// whole draft taken except the picked hero itself.
func finalSetState(m *Model, t sideTallies, ev DraftEvent, idx int) draftState {
	s := newDraftState()
	for _, x := range t.taken {
		if x != idx {
			s.taken = append(s.taken, x)
		}
	}
	s.banned = t.banned
	if ev.IsRadiant {
		for _, a := range t.radiantPool {
			if a != idx {
				s.allies = append(s.allies, a)
			}
		}
		for _, e := range t.direAll {
			s.addEnemy(e)
		}
	} else {
		for _, a := range t.direPool {
			if a != idx {
				s.allies = append(s.allies, a)
			}
		}
		for _, e := range t.radiantAll {
			s.addEnemy(e)
		}
	}
	s.buildSlugs(m)
	return s
}

func finishMatch(r *MatchReplay) {
	sum := 0.0
	for _, p := range r.Picks {
		if p.Radiant {
			sum += p.Score
		} else {
			sum -= p.Score
		}
	}
	r.Advantage = sum
}

// SequentialReplay walks every draft in pick order. At each pool pick the
// state is exactly what was visible then: the side's earlier pool picks as
// allies, every earlier opposing pick as the visible enemy set, and all
// earlier picks and bans taken.
func SequentialReplay(cfg *config.Config, m *Model, matches []Match) []MatchReplay {
	rules := gateRules(m.Gates)
	out := make([]MatchReplay, 0, len(matches))
	for _, mt := range matches {
		r := MatchReplay{MatchID: mt.ID, RadiantWin: mt.RadiantWin}
		for i, ev := range mt.Events {
			idx, ok := m.IdxOf[ev.Slug]
			if !ok || !ev.IsPick {
				continue
			}
			if _, pool := m.PoolPos[idx]; !pool {
				continue
			}
			p := scorePick(cfg, m, rules, stateBefore(m, mt, i), idx)
			p.MatchID, p.Seq, p.Radiant = mt.ID, ev.Seq, ev.IsRadiant
			r.Picks = append(r.Picks, p)
		}
		finishMatch(&r)
		out = append(out, r)
	}
	return out
}

// FinalSetReplay is the ablation twin: every pool pick is scored against
// the finished draft with itself left out, allies and enemies as final sets.
func FinalSetReplay(cfg *config.Config, m *Model, matches []Match) []MatchReplay {
	rules := gateRules(m.Gates)
	out := make([]MatchReplay, 0, len(matches))
	for _, mt := range matches {
		r := MatchReplay{MatchID: mt.ID, RadiantWin: mt.RadiantWin}
		t := tallySides(m, mt)
		for _, ev := range mt.Events {
			idx, ok := m.IdxOf[ev.Slug]
			if !ok || !ev.IsPick {
				continue
			}
			if _, pool := m.PoolPos[idx]; !pool {
				continue
			}
			p := scorePick(cfg, m, rules, finalSetState(m, t, ev, idx), idx)
			p.MatchID, p.Seq, p.Radiant = mt.ID, ev.Seq, ev.IsRadiant
			r.Picks = append(r.Picks, p)
		}
		finishMatch(&r)
		out = append(out, r)
	}
	return out
}
