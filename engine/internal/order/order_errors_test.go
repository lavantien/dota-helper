// writeCfgVariant writes the hub with the fixture pool spliced in plus one
// extra mutation. unlike writeFixtureConfig it does not load the result: the
// arms below need on-disk hubs that are parseable but fail hub validation, so
// Run's read-splice-validate chain meets the bad bytes where it should.
func writeCfgVariant(t *testing.T, path string, mut func(map[string]any)) []byte {
	t.Helper()
	raw, err := os.ReadFile("../../../config.json")
	if err != nil {
		t.Fatalf("read hub config: %v", err)
	}
	var hub map[string]any
	if err := json.Unmarshal(raw, &hub); err != nil {
		t.Fatalf("parse hub config: %v", err)
	}
	pb, err := json.Marshal(fixturePool())
	if err != nil {
		t.Fatalf("marshal fixture pool: %v", err)
	}
	var poolAny []any
	if err := json.Unmarshal(pb, &poolAny); err != nil {
		t.Fatalf("reparse fixture pool: %v", err)
	}
	hub["pool"] = poolAny
	if mut != nil {
		mut(hub)
	}
	out, err := json.MarshalIndent(hub, "", "  ")
	if err != nil {
		t.Fatalf("marshal variant config: %v", err)
	}
	out = append(out, '\n')
	if err := os.WriteFile(path, out, 0o644); err != nil {
		t.Fatalf("write variant config: %v", err)
	}
	return out
}

