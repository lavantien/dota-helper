func TestFindTopLevelValue(t *testing.T) {
	src := []byte("{\n  \"pool\": [\n  ],\n  \"other\": 1\n}")
	at, err := findTopLevelValue(src, "pool")
	if err != nil || src[at] != '[' {
		t.Fatalf("findTopLevelValue(pool) = %d, %v", at, err)
	}
	at, err = findTopLevelValue(src, "other")
	if err != nil || src[at] != '1' {
		t.Fatalf("findTopLevelValue(other) = %d, %v", at, err)
	}
	// tabs after the colon are skipped like spaces
	tabbed := []byte("{\n  \"k\":\t[1]\n}")
	at, err = findTopLevelValue(tabbed, "k")
	if err != nil || tabbed[at] != '[' {
		t.Fatalf("findTopLevelValue over a tab-padded value = %d, %v", at, err)
	}
	if _, err := findTopLevelValue(src, "gone"); err == nil || !strings.Contains(err.Error(), "not found") {
		t.Fatalf("missing key must fail, got %v", err)
	}
	amb := []byte("{\n  \"pool\": [],\n  \"pool\": []\n}")
	if _, err := findTopLevelValue(amb, "pool"); err == nil || !strings.Contains(err.Error(), "ambiguous") {
		t.Fatalf("duplicate key must fail, got %v", err)
	}
}

func TestMatchBracket(t *testing.T) {
	// every closer sits on the last byte, so the whole-span cases pin the scan
	flat := []byte("[1, 2]")
	if at, err := matchBracket(flat, 0); err != nil || at != len(flat)-1 {
		t.Fatalf("flat array close = %d, %v", at, err)
	}
	nested := []byte(`{"a": [1]}`)
	if at, err := matchBracket(nested, 0); err != nil || at != len(nested)-1 {
		t.Fatalf("nested object close = %d, %v", at, err)
	}
	// brackets inside string literals never count
	inStr := []byte(`["a]b"]`)
	if at, err := matchBracket(inStr, 0); err != nil || at != len(inStr)-1 {
		t.Fatalf("in-string bracket must be ignored, close = %d, %v", at, err)
	}
	// an escaped quote keeps the string open across a bracket
	escaped := []byte(`{"s": "a\"]"}`)
	if at, err := matchBracket(escaped, 0); err != nil || at != len(escaped)-1 {
		t.Fatalf("escaped-quote bracket must be ignored, close = %d, %v", at, err)
	}
	if _, err := matchBracket([]byte("[1"), 0); err == nil || !strings.Contains(err.Error(), "unmatched") {
		t.Fatalf("unterminated bracket must fail, got %v", err)
	}
	if _, err := matchBracket([]byte("x"), 0); err == nil || !strings.Contains(err.Error(), "expected a bracket") {
		t.Fatalf("non-bracket opener must fail, got %v", err)
	}
}

