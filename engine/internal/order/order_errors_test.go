// TestAssertConfigPreservedArms drives every disagreement the post-render
// audit rejects, plus the happy path, over hand-shaped documents.
func TestAssertConfigPreservedArms(t *testing.T) {
	entries := func(pairs ...[2]string) []any {
		var out []any
		for _, p := range pairs {
			out = append(out, map[string]any{"slug": p[0], "role": p[1]})
		}
		return out
	}
	mustMarshal := func(v any) []byte {
		b, err := json.Marshal(v)
		if err != nil {
			t.Fatalf("marshal: %v", err)
		}
		return b
	}
	ordered := func(slugs ...string) []config.PoolEntry {
		out := make([]config.PoolEntry, len(slugs))
		for i, s := range slugs {
			out[i] = config.PoolEntry{Slug: s, Role: "1"}
		}
		return out
	}
	ab := entries([2]string{"a", "1"}, [2]string{"b", "1"})
	flipped := entries([2]string{"b", "1"}, [2]string{"a", "1"})
	tests := []struct {
		name string
		orig []byte
		out  []byte
		want []config.PoolEntry
		err  string
	}{
		{"orig does not parse", []byte("{oops"), mustMarshal(map[string]any{"pool": ab}), nil, "invalid character"},
		{"out does not parse", mustMarshal(map[string]any{"pool": ab}), []byte("{oops"), nil, "does not parse"},
		{"changed top-level", mustMarshal(map[string]any{"pool": ab, "patch": "a"}),
			mustMarshal(map[string]any{"pool": ab, "patch": "b"}), nil, "changed top-level patch"},
		{"added top-level", mustMarshal(map[string]any{"pool": ab}),
			mustMarshal(map[string]any{"pool": ab, "zz": 1}), nil, "added top-level zz"},
		{"membership changed", mustMarshal(map[string]any{"pool": ab}),
			mustMarshal(map[string]any{"pool": entries([2]string{"a", "1"}, [2]string{"c", "1"})}), nil, "changed the pool membership"},
		{"order mismatch", mustMarshal(map[string]any{"pool": ab}),
			mustMarshal(map[string]any{"pool": flipped}), ordered("a", "b"), "does not match the computed order"},
		{"in order", mustMarshal(map[string]any{"pool": flipped}),
			mustMarshal(map[string]any{"pool": flipped}), ordered("b", "a"), ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := assertConfigPreserved(tt.orig, tt.out, tt.want)
			if tt.err == "" {
				if err != nil {
					t.Fatalf("matching documents must pass, got %v", err)
				}
				return
			}
			if err == nil || !strings.Contains(err.Error(), tt.err) {
				t.Fatalf("assertConfigPreserved must fail with %q, got %v", tt.err, err)
			}
		})
	}
}

